import logging
from typing import Any

import boto3
from botocore.exceptions import (
    ClientError,
    EndpointConnectionError,
    NoCredentialsError,
    NoRegionError,
    ParamValidationError,
    PartialCredentialsError,
)
from PIL import Image
from textractcaller import Textract_Features, call_textract
from textractcaller.t_call import Textract_Call_Mode
from textractor.entities.document import Document
from textractor.entities.table import Table
from textractor.parsers import response_parser

from exceptions import (
    AmazonTextractCredentialsException,
    AmazonTextractEndpointUnreachableException,
    AmazonTextractGenericException,
    AmazonTextractRegionException,
)
from logger import get_logger

logger: logging.Logger = get_logger(__name__)


def fix_generated_layouts_confidence(document: Document) -> None:
    """
    Fix confidence of layouts generated by textractor parser, they do not come from Amazon Textract response.
    Layouts split around table have confidence divided by 100 for each split, generated table layouts have 0.

    Args:
        document (Document): Parsed Amazon Textract document.
    """
    for layout in document.layouts:
        if layout.raw_object is not None:
            continue

        table = next((child for child in layout.children if isinstance(child, Table)), None)
        if table is not None:
            layout._confidence = table.confidence

        while 0 < layout._confidence < 0.01:
            layout._confidence *= 100


def process_image(aws_access_key_id: str, aws_secret_access_key: str, aws_region: str, image_path: str) -> Document:
    """
    Analyzes the document using Textract and returns the document object.

    Args:
        aws_access_key_id (str): AWS Access Key ID.
        aws_secret_access_key (str): AWS Secret Access Key.
        aws_region (str): AWS Region.
        image_path (str): Path to the image file to be analyzed.

    Returns:
        The document object containing the analysis results.
    """
    # @KA:action pdfix_autotag_textract pdfix_create_layout_template_json_textract
    # @KA:logic Pages are sent to Amazon Textract
    # @KA:desc Every page is sent as an image to Amazon Textract (layout and table analysis) in the
    # selected AWS region, one request per page, using your AWS keys. Pages leave your computer, an
    # internet connection is needed, and AWS charges for every page. The text that Amazon Textract
    # reads is used only to find regions on the page; the tags are created from the content of the
    # PDF itself, so scanned pages without a text layer need OCR first.
    # @KA:problem Amazon Textract processing failed. (error 30)
    # @KA:solution The log line above the error shows the message from Amazon. Check that the
    # region is selected and that Amazon Textract is enabled for your AWS account.
    #
    # @KA:param aws_id
    # @KA:desc AWS Access Key ID of an AWS account (user) that is allowed to use Amazon Textract.
    # Required.
    # @KA:problem "Amazon credentials problem. Please check the provided credentials." (error 31)
    # @KA:solution The key ID or secret key is wrong, empty or disabled. Copy both keys again from
    # your AWS account.
    #
    # @KA:param aws_secret
    # @KA:desc AWS Secret Access Key that belongs to the **AWS Access Key ID**. Required.
    #
    # @KA:param aws_region
    # @KA:desc AWS region where Amazon Textract is called (default `us-east-1`). Pick a region
    # close to you or one required by your data policy.
    # @KA:problem "Could not connect to the specified Amazon endpoint." (error 33)
    # @KA:solution There is no internet connection or Amazon Textract is not available in the
    # selected region. Check the connection or select another region.
    try:
        # Create boto3 Textract client
        textract_client: Any = boto3.client(
            "textract",
            aws_access_key_id=aws_access_key_id,
            aws_secret_access_key=aws_secret_access_key,
            region_name=aws_region,
        )

        # Inspired with arguments with what is in extractor.analyze_document only different boto3 client is used
        textract_json: dict = call_textract(
            input_document=image_path,
            features=[Textract_Features.TABLES, Textract_Features.LAYOUT],
            call_mode=Textract_Call_Mode.FORCE_SYNC,
            boto3_textract_client=textract_client,
            job_done_polling_interval=0,
        )

        # Created JSON needs to be further processed by textractor-parser to more useful format
        document: Document = response_parser.parse(textract_json)
        document.response = textract_json
        fix_generated_layouts_confidence(document)

        # Save image so visualization can be done later
        document.pages[0].image = Image.open(image_path)

    except NoCredentialsError as e:
        logger.error(f"{e}")
        raise AmazonTextractCredentialsException()
    except PartialCredentialsError as e:
        logger.error(f"{e}")
        raise AmazonTextractCredentialsException()
    except NoRegionError as e:
        logger.error(f"{e}")
        raise AmazonTextractRegionException()
    except EndpointConnectionError as e:
        logger.error(f"{e}")
        raise AmazonTextractEndpointUnreachableException()
    except ParamValidationError as e:
        logger.error(f"{e}")
        raise AmazonTextractGenericException()
    except ClientError as e:
        error_code = e.response["Error"]["Code"]
        if error_code in ["UnrecognizedClientException", "InvalidClientTokenId", "SignatureDoesNotMatch"]:
            logger.error(f"{e}")
            raise AmazonTextractCredentialsException()
        else:
            logger.error(f"{e}")
            raise AmazonTextractGenericException()
    except Exception as e:
        logger.error(f"{e}")
        raise AmazonTextractGenericException()

    return document
